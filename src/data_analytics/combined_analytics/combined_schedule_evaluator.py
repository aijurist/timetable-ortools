    def verify_ltp_constraints(self, data):
        """Verify Lecture-Tutorial-Practical constraints."""
        print("\n" + "="*80)
        print("🔍 LTP CONSTRAINT VERIFICATION")
        print("="*80)
        
        violations = []
        
        if data['course_requirements'] is None:
            print("❌ Cannot verify LTP constraints without course requirements")
            return {'success': False, 'violations': ['Missing course requirements']}
        
        # Create mapping of course requirements
        course_requirements = {}
        for _, row in data['course_requirements'].iterrows():
            instance_id = str(row['id'])
            course_requirements[instance_id] = {
                'lecture_hours': row['lecture_hours'],
                'practical_hours': row['practical_hours'],
                'tutorial_hours': row['tutorial_hours'],
                'course_code': row['course_code'],
                'course_name': row['course_name'],
                'teacher_id': row['teacher_id'],
                'student_count': row['student_count']
            }
        
        # Count scheduled hours per course instance
        scheduled_hours = defaultdict(lambda: {'lecture': 0, 'tutorial': 0, 'practical': 0})
        
        # Count theory assignments
        for _, row in data['theory_schedule'].iterrows():
            instance_id = str(row['course_instance_id'])
            session_type = row.get('session_type', 'lecture').lower()
            
            if session_type in ['lecture', 'theory']:
                scheduled_hours[instance_id]['lecture'] += 1
            elif session_type in ['tutorial', 'tut']:
                scheduled_hours[instance_id]['tutorial'] += 1
        
        # Count lab assignments (each lab session = 2 practical hours)
        for _, row in data['lab_schedule'].iterrows():
            instance_id = str(row['course_instance_id'])
            scheduled_hours[instance_id]['practical'] += 2
        
        # Verify constraints for each course
        compliant_courses = 0
        total_courses = 0
        
        print(f"{'ID':<6} {'Course':<12} {'L Req':<5} {'L Sch':<5} {'T Req':<5} {'T Sch':<5} {'P Req':<5} {'P Sch':<5} {'Status':<15}")
        print("-" * 85)
        
        for instance_id, requirements in course_requirements.items():
            total_courses += 1
            
            lecture_required = requirements['lecture_hours']
            tutorial_required = requirements['tutorial_hours']
            practical_required = requirements['practical_hours']
            
            lecture_scheduled = scheduled_hours[instance_id]['lecture']
            tutorial_scheduled = scheduled_hours[instance_id]['tutorial']
            practical_scheduled = scheduled_hours[instance_id]['practical']
            
            # Check compliance
            lecture_ok = lecture_scheduled >= lecture_required
            tutorial_ok = tutorial_scheduled >= tutorial_required
            practical_ok = practical_scheduled >= practical_required
            
            if lecture_ok and tutorial_ok and practical_ok:
                status = "✅ COMPLIANT"
                compliant_courses += 1
            else:
                status = "❌ VIOLATION"
                
                if not lecture_ok:
                    violations.append(f"Course {requirements['course_code']} (ID: {instance_id}): "
                                    f"Lecture shortage - need {lecture_required}, got {lecture_scheduled}")
                if not tutorial_ok:
                    violations.append(f"Course {requirements['course_code']} (ID: {instance_id}): "
                                    f"Tutorial shortage - need {tutorial_required}, got {tutorial_scheduled}")
                if not practical_ok:
                    violations.append(f"Course {requirements['course_code']} (ID: {instance_id}): "
                                    f"Practical shortage - need {practical_required}, got {practical_scheduled}")
            
            print(f"{instance_id:<6} {requirements['course_code']:<12} {lecture_required:<5} {lecture_scheduled:<5} "
                  f"{tutorial_required:<5} {tutorial_scheduled:<5} {practical_required:<5} {practical_scheduled:<5} {status:<15}")
        
        print("-" * 85)
        compliance_rate = (compliant_courses / total_courses) * 100 if total_courses > 0 else 0
        print(f"Compliance Rate: {compliant_courses}/{total_courses} ({compliance_rate:.1f}%)")
        
        # Save report
        report_path = os.path.join(self.analytics_dir, 'reports', 'ltp_constraints_report.txt')
        with open(report_path, 'w', encoding='utf-8') as f:
            f.write("LTP CONSTRAINT VERIFICATION REPORT\n")
            f.write("="*50 + "\n\n")
            f.write(f"Total Courses: {total_courses}\n")
            f.write(f"Compliant Courses: {compliant_courses}\n")
            f.write(f"Compliance Rate: {compliance_rate:.1f}%\n\n")
            f.write("VIOLATIONS:\n")
            for violation in violations:
                f.write(f"- {violation}\n")
        
        return {
            'success': len(violations) == 0,
            'compliance_rate': compliance_rate,
            'violations': violations,
            'total_courses': total_courses,
            'compliant_courses': compliant_courses
        }
    
    def verify_theory_lab_conflicts(self, data):
        """Verify that theory and lab groups don't conflict within same dept/semester."""
        print("\n" + "="*80)
        print("🔄 THEORY-LAB CONFLICT VERIFICATION")
        print("="*80)
        
        conflicts = []
        
        # Group theory sessions by department and semester
        theory_by_dept_sem = defaultdict(lambda: defaultdict(list))
        for _, session in data['theory_schedule'].iterrows():
            dept = session.get('department', 'Unknown')
            semester = session.get('semester', 0)
            group_index = session.get('group_index', 0)
            
            theory_by_dept_sem[dept][semester].append(session)
        
        # Group lab sessions by department and semester
        lab_by_dept_sem = defaultdict(lambda: defaultdict(list))
        for _, session in data['lab_schedule'].iterrows():
            dept = session.get('department', 'Unknown')
            semester = session.get('semester', 0)
            group_index = session.get('group_index', 0)
            
            lab_by_dept_sem[dept][semester].append(session)
        
        # Check for conflicts in each department-semester combination
        total_dept_sem = 0
        conflicted_dept_sem = 0
        
        for dept in set(list(theory_by_dept_sem.keys()) + list(lab_by_dept_sem.keys())):
            for semester in set(list(theory_by_dept_sem[dept].keys()) + list(lab_by_dept_sem[dept].keys())):
                if semester == 0 or dept == 'Unknown':
                    continue
                
                theory_sessions = theory_by_dept_sem[dept][semester]
                lab_sessions = lab_by_dept_sem[dept][semester]
                
                if not theory_sessions or not lab_sessions:
                    continue
                
                total_dept_sem += 1
                print(f"📋 Checking {dept} Semester {semester}:")
                print(f"   Theory sessions: {len(theory_sessions)}")
                print(f"   Lab sessions: {len(lab_sessions)}")
                
                # Check for time conflicts
                dept_conflicts = self._check_time_conflicts(theory_sessions, lab_sessions, dept, semester)
                if dept_conflicts:
                    conflicts.extend(dept_conflicts)
                    conflicted_dept_sem += 1
                    print(f"   ❌ Found {len(dept_conflicts)} conflicts")
                else:
                    print(f"   ✅ No conflicts")
        
        # Save conflict report
        report_path = os.path.join(self.analytics_dir, 'conflict_analysis', 'theory_lab_conflicts.txt')
        with open(report_path, 'w', encoding='utf-8') as f:
            f.write("THEORY-LAB CONFLICT ANALYSIS REPORT\n")
            f.write("="*50 + "\n\n")
            f.write(f"Total Department-Semester combinations checked: {total_dept_sem}\n")
            f.write(f"Combinations with conflicts: {conflicted_dept_sem}\n")
            f.write(f"Total conflicts found: {len(conflicts)}\n\n")
            f.write("CONFLICTS:\n")
            for conflict in conflicts:
                f.write(f"- {conflict}\n")
        
        print(f"\nConflict Summary: {len(conflicts)} conflicts in {conflicted_dept_sem}/{total_dept_sem} dept-sem combinations")
        
        return {
            'success': len(conflicts) == 0,
            'total_conflicts': len(conflicts),
            'conflicted_dept_sem': conflicted_dept_sem,
            'total_dept_sem': total_dept_sem,
            'conflicts': conflicts
        }
    
    def _check_time_conflicts(self, theory_sessions, lab_sessions, dept, semester):
        """Check for time conflicts between theory and lab sessions."""
        conflicts = []
        
        def parse_time_range(time_str):
            """Parse time range to start and end minutes."""
            try:
                start_str, end_str = time_str.split(' - ')
                
                def time_to_minutes(time_part):
                    hour, minute = map(int, time_part.split(':'))
                    return hour * 60 + minute
                
                return time_to_minutes(start_str), time_to_minutes(end_str)
            except:
                return None, None
        
        def time_ranges_overlap(start1, end1, start2, end2):
            """Check if two time ranges overlap."""
            if None in [start1, end1, start2, end2]:
                return False
            return start1 < end2 and start2 < end1
        
        # Check each theory session against each lab session
        for theory_session in theory_sessions:
            theory_day = theory_session.get('day')
            theory_timeslot = theory_session.get('time_slot', '')
            theory_group = theory_session.get('group_index', 0)
            
            for lab_session in lab_sessions:
                lab_day = lab_session.get('day')
                lab_session_name = lab_session.get('session_name', '')
                lab_group = lab_session.get('group_index', 0)
                
                # Only check sessions on the same day
                if theory_day == lab_day and theory_group == lab_group:
                    # Get theory time range
                    theory_start, theory_end = parse_time_range(theory_timeslot)
                    
                    # Get lab time range
                    if lab_session_name in self.lab_sessions:
                        lab_time_range = self.lab_sessions[lab_session_name]['time_range']
                        lab_start, lab_end = parse_time_range(lab_time_range)
                        
                        # Check for overlap
                        if time_ranges_overlap(theory_start, theory_end, lab_start, lab_end):
                            conflicts.append(
                                f"{dept} S{semester} G{theory_group}: Theory ({theory_timeslot}) "
                                f"conflicts with Lab {lab_session_name} ({lab_time_range}) on {theory_day}"
                            )
        
        return conflicts
    
