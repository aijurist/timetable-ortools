    def _create_timetable_visualization(self, groups, title, filename, is_theory=True):
        """Create a timetable visualization for group distributions."""
        plt.figure(figsize=(12, 8))
        
        # Create a matrix for the timetable
        num_days = len(self.days)
        num_slots = len(self.theory_slots) if is_theory else len(self.lab_sessions)
        
        # Initialize matrix
        timetable_matrix = np.zeros((num_slots, num_days))
        
        # Fill the matrix
        for group_name, sessions in groups.items():
            group_number = int(group_name[1:]) if group_name.startswith('G') else 1
            
            for _, session in enumerate(sessions):
                day = session.get('day')
                
                if day in self.days:
                    day_idx = self.days.index(day)
                    
                    if is_theory:
                        time_slot = session.get('time_slot', '')
                        if time_slot in self.theory_slots:
                            slot_idx = self.theory_slots.index(time_slot)
                            timetable_matrix[slot_idx, day_idx] = group_number
                    else:
                        session_name = session.get('session_name', '')
                        if session_name in self.lab_sessions:
                            slot_idx = list(self.lab_sessions.keys()).index(session_name)
                            timetable_matrix[slot_idx, day_idx] = group_number
        
        # Create the visualization
        im = plt.imshow(timetable_matrix, cmap='Set3', aspect='auto')
        
        plt.title(title, fontsize=14, fontweight='bold')
        plt.xlabel('Day')
        plt.ylabel('Time Slot')
        
        # Set labels
        plt.xticks(range(num_days), self.days, rotation=45)
        
        if is_theory:
            plt.yticks(range(num_slots), self.theory_slots)
        else:
            lab_labels = [f"{k} ({v['time_range']})" for k, v in self.lab_sessions.items()]
            plt.yticks(range(num_slots), lab_labels)
        
        # Add colorbar
        cbar = plt.colorbar(im)
        cbar.set_label('Group Number')
        
        plt.tight_layout()
        plt.savefig(filename, dpi=150, bbox_inches='tight')
        plt.close()
    
